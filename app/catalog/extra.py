def X(
    id,
    title,
    difficulty,
    points,
    tags,
    scenario,
    constraints,
    variables,
    resources,
    outputs,
    allowlist,
    tests,
    data_allow=None,
    starter=None,
    apply_sandbox=False,
):
    return {
        "id": id,
        "title": title,
        "difficulty": difficulty,
        "points": points,
        "tags": tags,
        "scenario": scenario,
        "constraints": constraints,
        "variables": variables,
        "expected_resources": resources,
        "expected_outputs": outputs,
        "allowlist": allowlist,
        "data_allowlist": data_allow or ["aws_region", "aws_caller_identity", "aws_iam_policy_document", "aws_ami"],
        "tests": tests,
        "starter": starter or {},
        "apply_sandbox": apply_sandbox,
    }


def E(id, type_, w=8, cat="Resources"):
    return T(id, f"{type_} is provisioned", cat, w, kind="resource_exists", type=type_)


def REF(id, resource, attr, ref, w=6):
    return T(id, f"{resource}.{attr} -> {ref}", "Resources", w, kind="attr_ref", resource=resource, attr=attr, ref=ref)


def EQ(id, resource, attr, value, w=6, cat="Resources"):
    return T(id, f"{resource}.{attr} = {value}", cat, w, kind="attr_equals", resource=resource, attr=attr, value=value)


def OUT(id, name, ref, w=5):
    return T(id, f"Output {name}", "Outputs", w, kind="output_ref", name=name, ref=ref)


def RQ(id="provider", name="aws", w=5):
    return T(id, f"Required provider {name}", "Providers", w, kind="required_provider", name=name)


def PR(id="region", provider="aws", attr="region", ref="var.aws_region", w=4):
    return T(id, f"{provider}.{attr} -> {ref}", "Providers", w, kind="provider_ref", provider=provider, attr=attr, ref=ref)


def VAR(id, name, type_=None, default=None, validation=False, w=3):
    return T(id, f"Variable {name}", "Variables", w, kind="var_defined", name=name, type=type_, default=default, validation=validation)


